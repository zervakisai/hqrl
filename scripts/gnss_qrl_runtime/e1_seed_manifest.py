"""The E1 seed manifest: every training, evaluation, baseline and stream seed of E1, frozen before any run.

    .venv/bin/python scripts/gnss_qrl_runtime/e1_seed_manifest.py --out <new directory>

Generated by the SAME functions the E1 runs execute (`CellRuntime.schedule`, `evaluation_seed`, `Study.stream`,
`e1_baselines.random_stream`) with the E1 study, so the frozen file and the executed schedule cannot disagree; a
test regenerates it and compares. `E1_FAIR_COMPARISON_PROPOSAL_EN.md` revision 2, section 3:

    namespaces      e1_training, e1_development, e1_evaluation: new, each 100,000 wide, after every P3 namespace
    blocks          tuning 0-2, evaluation 10-21 (N = 12), of e1_training; every other block is unused
    suites          e1_development realisations 0-4 (40 episodes), e1_evaluation realisations 0-9 (M = 10, 80)
    streams         every SeedSequence salted with E1_SALT, so none coincides with a P4 stream
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
for extra in (ROOT / 'src', ROOT / 'scripts', ROOT / 'scripts' / 'gnss_qrl_runtime'):
    if str(extra) not in sys.path:
        sys.path.insert(0, str(extra))

import p4_train as p4                                                                            # noqa: E402

MANIFEST_VERSION = 'gnss-e1-seed-manifest/1'
STUDY = p4.STUDIES['e1']
C = 'output/study/gnss_qrl_v1/frozen/'


def e1_runtime():
    return p4.CellRuntime(ROOT / (C + 'p3_freeze_v1/p3_frozen_configuration.json'),
                          ROOT / (C + 'p3_execution_manifest_v1/p3_execution_manifest.json'),
                          ROOT / 'output/training/time_model_village_v1/20260917T074923Z/time_model.json',
                          study=STUDY)


def suite_episodes(runtime, suite):
    """(cell, realisation, seed) of every episode of an E1 suite, in the frozen cell order."""
    namespace, realizations = STUDY.suites[suite]
    return [(cell, r, p4.evaluation_seed(runtime, namespace, cell, r)) for cell in runtime.cells for r in realizations]


def build(runtime):
    import e1_baselines
    if runtime.study is not STUDY:
        raise p4.P4Error('the E1 seed manifest is built from an E1 runtime only')
    blocks = {}
    for role, ids in STUDY.blocks.items():
        for b in ids:
            schedule = [[k, *(lambda cs: (cs[0]['cell_id'], cs[1]))(runtime.schedule(b, k))]
                        for k in range(p4.BLOCK_STRIDE)]
            blocks[str(b)] = {'role': role, 'streams': {'model_init': STUDY.stream(b, p4.INIT_STREAM),
                                                        'action_sampling': STUDY.stream(b, p4.ACTION_STREAM),
                                                        'minibatch_order': STUDY.stream(b, p4.MINIBATCH_STREAM)},
                              'schedule_sha256': hashlib.sha256(json.dumps(schedule).encode()).hexdigest(),
                              'schedule_first_10': schedule[:10],
                              'training_seeds': [schedule[0][2], schedule[-1][2]]}
    suites = {}
    for name in STUDY.suites:
        namespace, realizations = STUDY.suites[name]
        episodes = [{'cell_id': cell['cell_id'], 'realization': r, 'seed': seed,
                     'sample_streams': [STUDY.stream(p4.EVAL_STREAM, i, cell['cell_index'], r)
                                        for i in range(len(p4.CHECKPOINT_GRID_30K))],
                     'random_baseline_stream': e1_baselines.random_stream(name, cell, r)}
                    for cell, r, seed in suite_episodes(runtime, name)]
        suites[name] = {'namespace': namespace, 'realizations': list(realizations),
                        'checkpoint_grid': p4.CHECKPOINT_GRID_30K, 'episodes': episodes}
    return {'manifest_version': MANIFEST_VERSION, 'study': STUDY.name, 'salt': list(STUDY.salt),
            'execution_manifest_sha256': runtime.execution['manifest_sha256'],
            'training_namespace': STUDY.training_namespace, 'namespaces': runtime.namespaces,
            'frozen_p3_namespaces': runtime.execution['seed_namespaces'],
            'block_stride': p4.BLOCK_STRIDE,
            'rules': {'training_seed': f'{STUDY.training_namespace}.start + block * {p4.BLOCK_STRIDE} + episode',
                      'training_cell': f'frozen cell weights, SeedSequence([{p4.E1_SALT}, block, '
                                       f'{p4.SCHEDULE_STREAM}, episode])',
                      'streams': f'SeedSequence([{p4.E1_SALT}, block, stream]): init {p4.INIT_STREAM}, action '
                                 f'{p4.ACTION_STREAM}, minibatch {p4.MINIBATCH_STREAM}; the same for every arm and '
                                 'candidate of a block',
                      'evaluation_seed': 'p3_design.seed_for(namespace, seed_cell_index, realisation): the pair '
                                         'shares it',
                      'evaluation_sampling': f'SeedSequence([{p4.E1_SALT}, {p4.EVAL_STREAM}, checkpoint index, '
                                             'cell_index, realisation])',
                      'random_baseline': e1_baselines.RANDOM_STREAM_RULE,
                      'crn': 'run_p3_cells.crn_group(pair_id, namespace, seed), as in P3'},
            'blocks': blocks, 'suites': suites}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args(argv)
    if args.out.exists():
        raise SystemExit(f'{args.out} exists; never overwritten')
    manifest = build(e1_runtime())
    manifest['manifest_sha256'] = p4.canonical_sha256(manifest)
    args.out.mkdir(parents=True)
    path = args.out / 'e1_seed_manifest.json'
    path.write_text(json.dumps({'utc': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
                                'seed_manifest': manifest}, indent=1) + '\n')
    print(json.dumps({'path': str(path), 'manifest_sha256': manifest['manifest_sha256'],
                      'file_sha256': hashlib.sha256(path.read_bytes()).hexdigest()}, indent=1))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
